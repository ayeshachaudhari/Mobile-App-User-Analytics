-- Q24. Which app event has the highest number of occurrences in each country?

WITH event_counts AS (
    SELECT
        u.country,
        e.event_type,
        COUNT(*) AS total_events
    FROM users u
    JOIN events e
        ON u.user_id = e.user_id
    GROUP BY u.country, e.event_type
),
ranked_events AS (
    SELECT
        country,
        event_type,
        total_events,
        RANK() OVER (
            PARTITION BY country
            ORDER BY total_events DESC
        ) AS event_rank
    FROM event_counts
)
SELECT
    country,
    event_type,
    total_events
FROM ranked_events
WHERE event_rank = 1
ORDER BY country;


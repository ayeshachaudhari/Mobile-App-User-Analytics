CREATE TABLE users (
    user_id VARCHAR(10) PRIMARY KEY,
    name VARCHAR(100),
    age INT,
    gender VARCHAR(10),
    country VARCHAR(50),
    signup_date DATE
);

CREATE TABLE sessions (
    session_id VARCHAR(10) PRIMARY KEY,
    user_id VARCHAR(10),
    session_date DATE,
    duration_min INT,
    device VARCHAR(20),
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);

CREATE TABLE events (
    event_id VARCHAR(10) PRIMARY KEY,
    user_id VARCHAR(10),
    event_date DATE,
    event_type VARCHAR(50),
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);


CREATE TABLE purchases (
    purchase_id VARCHAR(10) PRIMARY KEY,
    user_id VARCHAR(10),
    purchase_date DATE,
    product VARCHAR(100),
    amount DECIMAL(10,2),
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);


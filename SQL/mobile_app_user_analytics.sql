-- Q30. Which country has the highest revenue per active user?

WITH country_revenue AS (
    SELECT
        u.country,
        SUM(p.amount) AS total_revenue
    FROM users u
    JOIN purchases p
        ON u.user_id = p.user_id
    GROUP BY u.country
),
country_active_users AS (
    SELECT
        u.country,
        COUNT(DISTINCT s.user_id) AS active_users
    FROM users u
    JOIN sessions s
        ON u.user_id = s.user_id
    GROUP BY u.country
)
SELECT
    r.country,
    r.total_revenue,
    a.active_users,
    ROUND(r.total_revenue / a.active_users, 2) AS revenue_per_active_user
FROM country_revenue r
JOIN country_active_users a
    ON r.country = a.country
ORDER BY revenue_per_active_user DESC
LIMIT 1;
